import { useState } from 'react';
import { explainFinding } from '../api';

export default function FindingExplanation({ findingId }) {
  const [loading, setLoading] = useState(false);
  const [data, setData] = useState(null);
  const [error, setError] = useState(null);

  const handleExplain = async () => {
    if (loading) return;
    setLoading(true);
    setError(null);
    try {
      const res = await explainFinding(findingId);
      setData(res);
    } catch (err) {
      setError(err.message || 'Failed to request explanation');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="explanation-container">
      {!data && !loading && (
        <button
          type="button"
          className="btn btn-secondary"
          onClick={handleExplain}
          style={{ display: 'inline-flex', alignItems: 'center', gap: '0.4rem' }}
        >
          <span>✨</span>
          <span>Explain in plain English</span>
        </button>
      )}

      {loading && (
        <div className="explanation-loading">
          <div className="spinner-sm" />
          <span>Generating, the first request can take up to a minute...</span>
        </div>
      )}

      {error && (
        <div className="explanation-unavailable">
          <strong>Notice: </strong>
          <span>{error}</span>
          <div style={{ marginTop: '0.5rem' }}>
            <button
              type="button"
              className="btn btn-secondary"
              onClick={handleExplain}
              style={{ fontSize: '0.8rem', padding: '0.25rem 0.5rem' }}
            >
              Retry
            </button>
          </div>
        </div>
      )}

      {data && (
        <div>
          {data.available ? (
            <div className="explanation-card">
              <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: '0.35rem' }}>
                <span className="explanation-badge">
                  Generated by {data.model || 'Ollama'} (Local)
                </span>
              </div>
              <span className="explanation-label">
                AI summary of the evidence above, generated locally. Check it against the evidence.
              </span>
              <p className="explanation-text">
                {data.explanation}
              </p>
            </div>
          ) : (
            <div className="explanation-unavailable">
              <strong>Local AI Explanation Unavailable: </strong>
              <span>
                {data.explanation || 'Please ensure Ollama is running locally at http://localhost:11434 with llama3.2.'}
              </span>
              <div style={{ marginTop: '0.5rem' }}>
                <button
                  type="button"
                  className="btn btn-secondary"
                  onClick={handleExplain}
                  style={{ fontSize: '0.8rem', padding: '0.25rem 0.5rem' }}
                >
                  Retry
                </button>
              </div>
            </div>
          )}
        </div>
      )}
    </div>
  );
}
