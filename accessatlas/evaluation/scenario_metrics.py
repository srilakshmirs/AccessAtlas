"""Scenario-level evaluation metrics for AccessAtlas M4 rules.

Compares findings generated by detection rules against GT_Labels:
- Per-scenario precision, recall, and F1 with raw counts (TP, FP, FN)
- Overall alert counts by rule and severity
- False-alarm rate per trap scenario with raw counts (flagged / total)
- Explicit reporting of uncovered holdout scenarios (not covered)
- Mapping of internal identifiers to GT identifiers strictly inside evaluation.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import pandas as pd

from accessatlas.graph import build_privilege_graph, compute_identity_privileges
from accessatlas.ingestion.loader import load_table
from accessatlas.resolution import resolve_identities
from accessatlas.rules.detectors import evaluate_all_rules
from accessatlas.rules.models import Finding
from accessatlas.utils import load_config

logger = logging.getLogger(__name__)

# Canonical mapping from rule name to GT anomaly scenario name
RULE_TO_SCENARIO: dict[str, str] = {
    "offboarding_gap": "offboarding_gap",
    "orphan_account": "orphan_account",
    "dormant_admin": "dormant_admin",
    "expired_exception_active": "expired_exception_active",
    "stale_token": "stale_token",
    "nested_group_escalation": "nested_group_escalation",
    "cross_platform_admin": "cross_platform_admin",
    "orphaned_service_account": "orphaned_service_account",
}

# Scenarios that have no rule in the rules-only baseline
UNCOVERED_SCENARIOS: dict[str, str] = {
    "excessive_service_privilege": "Static rule scope limited to orphaned service accounts; excessive service privileges require behavioral profiling.",
    "privilege_creep": "Requires behavioral temporal modeling across sequential role transfers (ML component).",
    "token_misuse": "Requires behavioral audit log analysis (unusual IPs, anomalous off-hours bursts) (ML component).",
}

# The 5 trap scenarios designed to test suppression mechanisms
TRAP_SCENARIOS: list[str] = [
    "approved_exception_active",
    "oncall_engineer",
    "legit_offboarding_extension",
    "scheduled_night_job",
    "new_hire_admin",
]


@dataclass
class ScenarioMetrics:
    scenario: str
    covered: bool
    tp: int = 0
    fp: int = 0
    fn: int = 0
    precision: float = 0.0
    recall: float = 0.0
    f1: float = 0.0
    notes: str = ""


@dataclass
class TrapMetrics:
    scenario: str
    total_traps: int = 0
    flagged_traps: int = 0
    false_alarm_rate: float = 0.0
    has_firing_rule: bool = True
    notes: str = ""


@dataclass
class SplitEvaluationReport:
    split: str
    total_identities: int
    total_findings: int
    findings_by_rule: dict[str, int] = field(default_factory=dict)
    findings_by_severity: dict[str, int] = field(default_factory=dict)
    scenarios: dict[str, ScenarioMetrics] = field(default_factory=dict)
    traps: dict[str, TrapMetrics] = field(default_factory=dict)

    def print_summary(self) -> None:
        """Print a formatted evaluation table."""
        print("\n================================================================================")
        print(f"M4 SCENARIO EVALUATION REPORT — Split: {self.split.upper()}")
        print("================================================================================")
        print(f"Total Identities: {self.total_identities} | Total Findings: {self.total_findings}")
        print(f"Findings by Rule: {self.findings_by_rule}")
        print(f"Findings by Severity: {self.findings_by_severity}")

        print("\n--- Anomaly Scenarios Performance ---")
        headers = f"{'Scenario':<30} {'Status':<12} {'TP':<5} {'FP':<5} {'FN':<5} {'Precision':<10} {'Recall':<10} {'F1':<10}"
        print(headers)
        print("-" * len(headers))
        for scen, sm in sorted(self.scenarios.items()):
            status = "Covered" if sm.covered else "Not Covered"
            prec_str = f"{sm.precision:.4f}" if sm.covered and (sm.tp + sm.fp > 0) else "N/A"
            rec_str = f"{sm.recall:.4f}" if sm.covered and (sm.tp + sm.fn > 0) else "N/A"
            f1_str = f"{sm.f1:.4f}" if sm.covered and (sm.tp + sm.fp + sm.fn > 0) else "N/A"
            print(
                f"{scen:<30} {status:<12} {sm.tp:<5} {sm.fp:<5} {sm.fn:<5} {prec_str:<10} {rec_str:<10} {f1_str:<10}"
            )

        print("\n--- Trap Scenarios (False-Alarm Rate) ---")
        trap_headers = f"{'Trap Scenario':<32} {'Total':<8} {'Flagged':<8} {'FAR (%)':<10} {'Firing Rule Status'}"
        print(trap_headers)
        print("-" * len(trap_headers))
        for trap, tm in sorted(self.traps.items()):
            far_str = f"{tm.false_alarm_rate * 100:.2f}%" if tm.has_firing_rule else "N/A"
            rule_status = (
                "Rule exists (suppressed)" if tm.has_firing_rule else "No static rule fires"
            )
            print(
                f"{trap:<32} {tm.total_traps:<8} {tm.flagged_traps:<8} {far_str:<10} {rule_status}"
            )


def load_gt_scenario_data(
    gt_dir: str | Path = "data/processed/gt",
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Load GT_Labels and GT_IdentityLinks for scenario evaluation.

    Strictly isolated inside accessatlas/evaluation/.
    """
    p_labels = Path(gt_dir) / "GT_Labels.parquet"
    p_links = Path(gt_dir) / "GT_IdentityLinks.parquet"
    if not p_labels.exists() or not p_links.exists():
        raise FileNotFoundError(f"GT parquet files missing from {gt_dir}")
    return pd.read_parquet(p_labels), pd.read_parquet(p_links)


def evaluate_scenario_findings(
    findings: list[Finding],
    gt_labels_df: pd.DataFrame,
    gt_links_df: pd.DataFrame,
    split: str = "train",
) -> SplitEvaluationReport:
    """Evaluate findings against ground truth labels for a specific split.

    Maps our internal identifiers (`employee_id`, `svc:<plat>:<acc>`, `account_id`)
    to GT identity IDs strictly inside this function.
    """
    # Filter GT labels by split if split != "all"
    if split != "all":
        split_labels = gt_labels_df[gt_labels_df["split"] == split].copy()
    else:
        split_labels = gt_labels_df.copy()

    split_ids = set(split_labels["identity_id"].astype(str))

    # Build account_id -> GT identity_id mapping
    acc_to_gt: dict[str, str] = {}
    for _, row in gt_links_df.iterrows():
        iid = str(row["identity_id"])
        for col in ["ad_account_id", "aws_user_id", "okta_id"]:
            val = row.get(col)
            if pd.notna(val) and val:
                acc_to_gt[str(val)] = iid

    # Map findings to GT identity IDs and keep findings within this split
    mapped_findings_by_rule: dict[str, set[str]] = {}
    total_split_findings = 0
    by_rule_count: dict[str, int] = {}
    by_sev_count: dict[str, int] = {}

    for f in findings:
        our_id = f.identity_id
        if our_id.startswith("svc:"):
            acc_id = our_id.split(":")[-1]
            gt_id = acc_to_gt.get(acc_id, our_id)
        elif our_id in acc_to_gt:
            gt_id = acc_to_gt[our_id]
        else:
            gt_id = our_id

        if gt_id in split_ids:
            total_split_findings += 1
            by_rule_count[f.rule] = by_rule_count.get(f.rule, 0) + 1
            by_sev_count[f.severity] = by_sev_count.get(f.severity, 0) + 1
            mapped_findings_by_rule.setdefault(f.rule, set()).add(gt_id)

    # 1. Anomaly Scenarios Evaluation
    scenarios_result: dict[str, ScenarioMetrics] = {}

    # All known anomaly scenarios across splits
    all_anomaly_scenarios = set(split_labels[split_labels["is_anomaly"] == 1]["scenario"].unique())
    # Add known uncovered scenarios to guarantee they appear in the report
    for unc in UNCOVERED_SCENARIOS:
        if unc in set(gt_labels_df["scenario"]):
            all_anomaly_scenarios.add(unc)
    for rule, scen in RULE_TO_SCENARIO.items():
        all_anomaly_scenarios.add(scen)

    for scen in sorted(all_anomaly_scenarios):
        scen_rows = split_labels[split_labels["scenario"] == scen]
        true_entities = set(scen_rows[scen_rows["is_anomaly"] == 1]["identity_id"].astype(str))

        # Check if rule exists
        matching_rule = None
        for r_name, s_name in RULE_TO_SCENARIO.items():
            if s_name == scen:
                matching_rule = r_name
                break

        if matching_rule is None or scen in UNCOVERED_SCENARIOS:
            # Uncovered scenario
            fn = len(true_entities)
            scenarios_result[scen] = ScenarioMetrics(
                scenario=scen,
                covered=False,
                tp=0,
                fp=0,
                fn=fn,
                precision=0.0,
                recall=0.0,
                f1=0.0,
                notes=UNCOVERED_SCENARIOS.get(scen, "No detection rule implemented"),
            )
            continue

        flagged_entities = mapped_findings_by_rule.get(matching_rule, set())
        tp_set = flagged_entities.intersection(true_entities)
        fp_set = flagged_entities.difference(true_entities)
        fn_set = true_entities.difference(flagged_entities)

        tp = len(tp_set)
        fp = len(fp_set)
        fn = len(fn_set)

        prec = tp / (tp + fp) if (tp + fp) > 0 else 0.0
        rec = tp / (tp + fn) if (tp + fn) > 0 else 0.0
        f1 = (2 * prec * rec) / (prec + rec) if (prec + rec) > 0 else 0.0

        scenarios_result[scen] = ScenarioMetrics(
            scenario=scen,
            covered=True,
            tp=tp,
            fp=fp,
            fn=fn,
            precision=prec,
            recall=rec,
            f1=f1,
        )

    # 2. Trap Scenarios Evaluation
    trap_results: dict[str, TrapMetrics] = {}

    for trap in TRAP_SCENARIOS:
        trap_rows = split_labels[split_labels["scenario"] == trap]
        total_traps = len(trap_rows)
        if total_traps == 0:
            continue

        trap_eids = set(trap_rows["identity_id"].astype(str))

        # Check how many were flagged by ANY anomaly detection rule (excluding low-severity unlinked review)
        flagged_traps = 0
        for r_name in RULE_TO_SCENARIO:
            flagged_for_rule = mapped_findings_by_rule.get(r_name, set())
            flagged_traps += len(flagged_for_rule.intersection(trap_eids))

        # Check whether any static rule targets this trap
        has_firing_rule = trap != "scheduled_night_job"
        far = flagged_traps / total_traps if total_traps > 0 and has_firing_rule else 0.0

        trap_results[trap] = TrapMetrics(
            scenario=trap,
            total_traps=total_traps,
            flagged_traps=flagged_traps,
            false_alarm_rate=far,
            has_firing_rule=has_firing_rule,
            notes="" if has_firing_rule else "No static rule fires (behavioral event trap)",
        )

    return SplitEvaluationReport(
        split=split,
        total_identities=len(split_labels),
        total_findings=total_split_findings,
        findings_by_rule=by_rule_count,
        findings_by_severity=by_sev_count,
        scenarios=scenarios_result,
        traps=trap_results,
    )


def run_full_scenario_evaluation(
    splits: tuple[str, ...] = ("train",),
    config: dict[str, Any] | None = None,
) -> dict[str, SplitEvaluationReport]:
    """Execute end-to-end detection pipeline and evaluate on requested split(s)."""
    cfg = config or load_config()

    # Load core data
    hr = load_table("HR_Records", config=cfg)
    hr_off = load_table("HR_Offboarding", config=cfg)
    role_changes = load_table("HR_RoleChanges", config=cfg)
    ad = load_table("AD_Users", config=cfg)
    aws = load_table("AWS_Users", config=cfg)
    okta = load_table("Okta_Users", config=cfg)
    exc = load_table("Exceptions", config=cfg)
    oncall = load_table("OnCall_Roster", config=cfg)
    jobs = load_table("Scheduled_Jobs", config=cfg)
    tokens = load_table("API_Tokens", config=cfg)
    tier_map = load_table("Tier_Mapping", config=cfg)
    audit = load_table("Audit_Events", config=cfg, validate=False)

    # Resolve identities (M2)
    res = resolve_identities(hr, ad, aws, okta)
    res_df = res.resolved_identities
    unres_df = res.unresolved_accounts

    # Build privilege graph (M3)
    graph = build_privilege_graph(
        ad_groups_df=load_table("AD_Groups", config=cfg),
        ad_membership_df=load_table("AD_GroupMembership", config=cfg),
        aws_groups_df=load_table("AWS_Groups", config=cfg),
        aws_policies_df=load_table("AWS_Policies", config=cfg),
        aws_user_groups_df=load_table("AWS_UserGroups", config=cfg),
        aws_policy_attach_df=load_table("AWS_PolicyAttach", config=cfg),
        okta_admin_roles_df=load_table("Okta_AdminRoles", config=cfg),
        okta_group_membership_df=load_table("Okta_GroupMembership", config=cfg),
        okta_aws_federation_df=load_table("Okta_AWS_Federation", config=cfg),
        tier_mapping_df=tier_map,
        ad_users_df=ad,
        aws_users_df=aws,
        okta_users_df=okta,
    )
    priv_df = compute_identity_privileges(graph, res_df)

    # Evaluate rules (M4)
    findings = evaluate_all_rules(
        hr_df=hr,
        hr_offboarding_df=hr_off,
        ad_users_df=ad,
        aws_users_df=aws,
        okta_users_df=okta,
        resolved_identities=res_df,
        unresolved_accounts=unres_df,
        privilege_df=priv_df,
        audit_events_df=audit,
        exceptions_df=exc,
        oncall_df=oncall,
        scheduled_jobs_df=jobs,
        role_changes_df=role_changes,
        tokens_df=tokens,
        config=cfg,
    )

    # Load GT data
    gt_labels, gt_links = load_gt_scenario_data()

    reports: dict[str, SplitEvaluationReport] = {}
    for split in splits:
        report = evaluate_scenario_findings(findings, gt_labels, gt_links, split=split)
        report.print_summary()
        reports[split] = report

    return reports
